"""``TPrincipal``: principal component analysis, as ROOT's class does it.

ROOT keeps the covariance of the rows it is given, decomposes it and orders the components by
eigenvalue, so a macro can change a point into principal components and back. The numbers here
are ROOT's - the same rows give the same means, sigmas and eigenvectors to the digits its table
prints - because the arithmetic is the same: sums accumulated row by row, the population sigma,
the correlation matrix when the ``N`` option normalises, and a symmetric eigen-decomposition
ordered largest first. ``Print`` and ``MakeCode`` write ROOT's own layout, so a macro that reads
either reads what ROOT writes.
"""

from __future__ import annotations

import sys
import time
from typing import Any

import numpy as np

from .objects import TObject

__all__ = ["TPrincipal"]

#: What ``Print`` writes above the table, as ROOT writes it.
_HEADER = (
    " Variable #  | Mean Value |   Sigma    | Eigenvalue\n"
    "-------------+------------+------------+------------"
)

#: ``MakeCode``'s file, split around the four arrays of numbers it carries: the fixed text and
#: the name of the array that goes after it, alternating. Every byte is ROOT's own, trailing
#: spaces included, so the file a macro reads is the file ROOT writes.
_PARTS = (
    "// -*- mode: c++ -*-\n"
    "// \n"
    "// File {name} generated by TPrincipal::MakeCode\n"
    "// on {date}\n"
    "// ROOT version {version}\n"
    "//\n"
    "// This file contains the functions \n"
    "//\n"
    "//    void  X2P(Double_t *x, Double_t *p); \n"
    "//    void  P2X(Double_t *p, Double_t *x, Int_t nTest);\n"
    "//\n"
    "// The first for transforming original data x in \n"
    "// pattern space, to principal components p in \n"
    "// feature space. The second function is for the\n"
    "// inverse transformation, but using only nTest\n"
    "// of the principal components in the expansion\n"
    "// \n"
    "// See TPrincipal class documentation for more information \n"
    "// \n"
    "#include <Rtypes.h> // needed for Double_t etc\n"
    "//\n"
    "// Static data variables\n"
    "//\n"
    "static Int_t    gNVariables = {variables};\n"
    "\n"
    "// Assignment of eigenvector matrix.\n"
    "// Elements are stored row-wise, that is\n"
    "//    M[i][j] = e[i * nVariables + j] \n"
    "// where i and j are zero-based\n",
    'gEigenVectors',
    "// Assignment to eigen value vector. Zero-based.\n",
    'gEigenValues',
    "// Assignment to mean value vector. Zero-based.\n",
    'gMeanValues',
    "// Assignment to sigma value vector. Zero-based.\n",
    'gSigmaValues',
    "// \n"
    "// The function   void X2P(Double_t *x, Double_t *p)\n"
    "// \n"
    "void X2P(Double_t *x, Double_t *p) {\n"
    "  for (Int_t i = 0; i < gNVariables; i++) {\n"
    "    p[i] = 0;\n"
    "    for (Int_t j = 0; j < gNVariables; j++)\n"
    "      p[i] += (x[j] - gMeanValues[j]) \n"
    "        * gEigenVectors[j *  gNVariables + i] / gSigmaValues[j];\n"
    "\n"
    "  }\n"
    "}\n"
    "\n"
    "// \n"
    "// The function   void P2X(Double_t *p, Double_t *x, Int_t nTest)\n"
    "// \n"
    "void P2X(Double_t *p, Double_t *x, Int_t nTest) {\n"
    "  for (Int_t i = 0; i < gNVariables; i++) {\n"
    "    x[i] = gMeanValues[i];\n"
    "    for (Int_t j = 0; j < nTest; j++)\n"
    "      x[i] += p[j] * gSigmaValues[i] \n"
    "        * gEigenVectors[i *  gNVariables + j];\n"
    "  }\n"
    "}\n"
    "\n"
    "// EOF for {name}\n"
    "\n",
)


def _filled(text: str, **values: str) -> str:
    """``text`` with ROOT's ``{name}`` placeholders replaced - by hand, so C++'s braces stay."""
    for key, value in values.items():
        text = text.replace("{" + key + "}", value)
    return text


def _numbers(values: Any) -> str:
    """One array of numbers as ROOT writes it: ``%g`` each, indented two, a comma between."""
    return ",\n".join(f"  {value:g}" for value in np.asarray(values).reshape(-1))


class TPrincipal(TObject):
    """``TPrincipal``: the covariance of the rows added, and its principal components."""

    def __init__(self, nvariables: Any = 0, option: Any = "") -> None:
        super().__init__()
        self._n = int(nvariables)
        self._option = str(option)
        self._rows = 0
        self._sums = np.zeros(self._n)
        self._outer = np.zeros((self._n, self._n))
        self._means = np.zeros(self._n)
        self._sigmas = np.zeros(self._n)
        self._eigenvalues = np.zeros(self._n)
        self._eigenvectors = np.zeros((self._n, self._n))

    def __repr__(self) -> str:
        return f"<TPrincipal {self._n} variables, {self._rows} rows>"

    # -- filling ----------------------------------------------------------------------------

    def AddRow(self, row: Any) -> None:
        """``AddRow``: one row of ``nvariables`` numbers, accumulated into the sums."""
        values = np.asarray(row, dtype=np.float64).reshape(-1)[: self._n]
        if len(values) != self._n:
            raise ValueError(
                f"TPrincipal has {self._n} variables, and AddRow was given {len(values)} values"
            )
        self._sums += values
        self._outer += np.outer(values, values)
        self._rows += 1

    # -- the decomposition ------------------------------------------------------------------

    def MakePrincipals(self) -> int:
        """``MakePrincipals``: means, sigmas and eigenvectors from the rows added; always ``0``."""
        if not self._rows:
            return 0
        count = float(self._rows)
        self._means = self._sums / count
        # ROOT's sigma is the population one: the mean square less the mean's own square.
        variance = np.diag(self._outer) / count - self._means**2
        self._sigmas = np.sqrt(np.maximum(variance, 0.0))
        covariance = self._outer / count - np.outer(self._means, self._means)
        if "N" in self._option:  # the correlation matrix, as ROOT's N option asks for
            spread = np.outer(self._sigmas, self._sigmas)
            scaled = np.where(spread > 0, covariance / np.where(spread > 0, spread, 1.0), 0.0)
            covariance = scaled
        values, vectors = np.linalg.eigh((covariance + covariance.T) / 2)
        order = np.argsort(values)[::-1]
        self._eigenvalues = values[order] / self._n  # ROOT reports each as a share of the whole
        self._eigenvectors = vectors[:, order]
        return 0

    # -- what ROOT writes -------------------------------------------------------------------

    def Print(self, option: Any = "") -> None:
        """``Print``: each variable's mean, sigma and eigenvalue, in ROOT's own table."""
        said = [_HEADER]
        for at in range(self._n):
            said.append(
                f"{at:12d} | {self._means[at]:10.4g} | {self._sigmas[at]:10.4g} | "
                f"{self._eigenvalues[at]:10.4g} "
            )
        sys.stdout.write("\n".join(said) + "\n\n")
        sys.stdout.flush()  # ROOT's C++ output does not wait for Python's buffer

    def Test(self) -> int:
        """``Test``: a row changed into components and back; ``0`` when they round-trip."""
        if not self._rows:
            return 0
        row = self._sums / self._rows
        return 0 if np.allclose(self.P2X(self.X2P(row)), row, atol=1e-9) else 1

    def X2P(self, row: Any) -> Any:
        """``X2P``: the principal components of a row, as the generated ``X2P`` computes them."""
        values = (np.asarray(row, dtype=np.float64).reshape(-1) - self._means) / self._sigmas
        return self._eigenvectors.T @ values

    def P2X(self, pattern: Any) -> Any:
        """``P2X``: the row a set of components stands for, as the generated ``P2X`` does."""
        values = np.asarray(pattern, dtype=np.float64).reshape(-1)
        return self._means + self._sigmas * (self._eigenvectors @ values)

    def MakeHistograms(self) -> None:
        """``MakeHistograms``: a histogram of each variable over its mean and three sigmas either
        side, kept in the current directory, which is what ROOT leaves a browser to look at."""
        from .hists import TH1D

        for at in range(self._n):
            centre, spread = float(self._means[at]), float(self._sigmas[at])
            low, high = centre - 3 * spread, centre + 3 * spread
            TH1D(f"h_{at}", f"Original variable {at}", 100, low, high)

    def MakeCode(self, filename: Any = "pca.C") -> None:
        """``MakeCode``: ROOT's own C++ file, which changes a row into components and back."""
        from .troot import gROOT

        flat = self._eigenvectors.reshape(-1)  # ROOT keeps component i of vector j at i*n+j
        name = str(filename)
        sys.stdout.write(f'\nWriting on file "{name}" ... ')
        arrays = (flat, self._eigenvalues, self._means, self._sigmas)
        said = [_filled(_PARTS[0], name=name, variables=str(self._n))]
        for at, values in enumerate(arrays):
            said.append(
                f"static Double_t {_PARTS[2 * at + 1]}[] = {{\n{_numbers(values)}}};\n"
            )
            said.append(_filled(_PARTS[2 * at + 2], name=name))
        text = _filled("".join(said), name=name,
                       date=time.strftime("%a %b %d %H:%M:%S %Y", time.localtime()),
                       version=gROOT.GetVersion())  # fmt: skip
        with open(name, "w") as out:
            out.write(text)
        sys.stdout.write("done\n")
        sys.stdout.flush()
