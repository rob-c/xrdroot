"""roottest's macros - ``ROOTTEST_ADD_TEST`` and the setup steps around it - as what they register.

``ROOTTEST_ADD_TEST`` (RootMacros.cmake:3097) turns a ``MACRO``, ``EXEC`` or
``COMMAND`` into a ``root.exe -b -q`` or other command line wrapped in the
test driver, which captures standard output (and error) and diffs it against
an ``OUTREF`` with ``roottest/scripts/custom_diff.py``. The handlers here
keep the parts that decide how a test runs and is judged, the ctest name it
gets (``roottest-root-io-tree-read``), and the setup steps - a macro compiled
by ACLiC, a dictionary generated by rootcling or genreflex, an executable
built - which become tests of their own, as they are in ctest's count, each
running the ``xrdroot build`` command that stands in for it
(:mod:`~tools.rootsuite.builds`).
"""

from __future__ import annotations

import os
import re
from pathlib import Path

from . import builds
from .cmake import DEFINITIONS, HANDLERS, Directory, parse_arguments
from .model import Dictionary, Target, Test, kind_of, make_id
from .rootmacros import generate_dictionary, library, register_command, sources, working_dir

__all__ = ["targetname", "prefix", "add_test"]

#: ``ROOTTEST_ADD_TEST``'s keywords: options, one-value, many-value.
_KEYWORDS = (
    ["WILLFAIL", "RUN_SERIAL", "STOREOUT"],
    ["OUTREF", "ERRREF", "OUTREF_CINTSPECIFIC", "OUTCNV", "PASSRC", "MACROARG", "WORKING_DIR",
     "INPUT", "ENABLE_IF", "DISABLE_IF", "TIMEOUT", "RESOURCE_LOCK"],
    ["TESTOWNER", "COPY_TO_BUILDDIR", "MACRO", "ROOTEXE_OPTS", "EXEC", "COMMAND", "PRECMD",
     "POSTCMD", "OUTCNVCMD", "FAILREGEX", "PASSREGEX", "DEPENDS", "OPTS", "LABELS",
     "ENVIRONMENT", "FIXTURES_SETUP", "FIXTURES_CLEANUP", "FIXTURES_REQUIRED", "PROPERTIES",
     "PYTHON_DEPS"],
)  # fmt: skip

#: The extensions ``ROOTTEST_SETUP_MACROTEST`` hands to ``root.exe`` as C++ macros.
_CXX = (".C", ".cxx", ".cpp", ".cc")


def targetname(self: Directory, filename: str) -> str:
    """``ROOTTEST_TARGETNAME_FROM_FILE``: the file's directory below ROOT, dashed, and its stem.

    For ``.`` - the directory itself - that is the prefix of every test name
    there, ``roottest-root-io-tree``; the macro's string replace of the file
    name then also drops any dot in the directory, as here.
    """
    real = os.path.normpath(f"{self.relative}/{filename}")
    stripped = real.replace(filename, "") if filename != "." else real.replace(".", "")
    stem = Path(filename).name.split(".")[0]
    return (stripped + stem).replace("/", "-")


def prefix(self: Directory) -> str:
    return targetname(self, ".")


def _short(self: Directory, ctest: str) -> str:
    """The test's name within its directory: its ctest name without the directory's prefix."""
    head = prefix(self) + "-"
    return ctest[len(head):] if ctest.startswith(head) else ctest


def _setup(self: Directory, ctest: str, of: str, files: list[str],
           parsed: dict[str, list[str]], **more: object) -> None:
    """A build step ctest runs as a test: compiling a macro, a dictionary, an executable.

    What it runs is ``more["builds"]``; an executable's are only known once
    every library it may link is registered, so it names its ``program``.
    """
    if any(test.ctest == ctest for test in self.registry.tests):
        return
    self.registry.add(Test(
        id=make_id("roottest", self.relative, _short(self, ctest)), ctest=ctest,
        kind=kind_of(ctest, self.relative), directory=self.relative, runner="setup",
        files=tuple(files), fixtures_setup=tuple(parsed.get("FIXTURES_SETUP", [])),
        fixtures_required=tuple(parsed.get("FIXTURES_REQUIRED", [])), setup_of=of,
        check_out=False, check_err=False, **more))  # type: ignore[arg-type]


def _compile_macro(self: Directory, args: list[str]) -> str:
    """``ROOTTEST_COMPILE_MACRO(file)``: ACLiC builds it, as test ``<prefix>-<stem>-build``.

    roottest's ``scripts/build.C`` calls ``gSystem->CompileMacro(file, "kc")``,
    and the test fails on any ``Warning in``.
    """
    parsed = parse_arguments(args[1:], [], ["BUILDOBJ", "BUILDLIB"], _FIXTURE_KEYS)
    ctest = targetname(self, args[0]) + "-build"
    macro = self.relative_path(args[0])
    _setup(self, ctest, "compiled-macro", [macro], parsed,
           builds=(builds.aclic(self.relative, macro),), failregex=("Warning in",))
    self.variables["COMPILE_MACRO_TEST"] = ctest
    return ctest


def _compile_macro_command(self: Directory, args: list[str]) -> None:
    if args:
        _compile_macro(self, args)


_FIXTURE_KEYS = ["FIXTURES_SETUP", "FIXTURES_CLEANUP", "FIXTURES_REQUIRED"]


def _dictionary(self: Directory, args: list[str]) -> None:
    """``ROOTTEST_GENERATE_DICTIONARY(name headers... [LINKDEF l] [SOURCES s...])``.

    rootcling makes ``name.cxx``, compiled with the sources into ``name.so``
    (no ``lib`` added), by test ``<prefix>-<name>-build``; executables link
    it as target ``<name>libgen``.
    """
    if not args:
        return
    parsed = parse_arguments(args[1:], ["NO_ROOTMAP", "NO_CXXMODULE"], _FIXTURE_KEYS,
                             ["LINKDEF", "SOURCES", "DEPENDS", "OPTIONS", "COMPILE_OPTIONS"])
    ctest = targetname(self, args[0]) + "-build"
    entry = generate_dictionary(self, [args[0], *parsed["UNPARSED"], "MODULE", args[0],
                                       "LINKDEF", *parsed.get("LINKDEF", [])[:1]])
    target = library(self, args[0] + "libgen", sources(self, parsed.get("SOURCES", [])), [],
                     output=builds.library_name(args[0]))
    target.dictionaries.append(entry)
    target.dictionary = True
    _setup(self, ctest, "dictionary", sources(self, parsed["UNPARSED"]), parsed,
           builds=tuple(builds.library(self.registry, target)))
    self.targets.update({args[0], args[0] + "libgen"})
    self.variables["GENERATE_DICTIONARY_TEST"] = ctest


def _reflex_dictionary(self: Directory, args: list[str]) -> None:
    """``ROOTTEST_GENERATE_REFLEX_DICTIONARY(name headers... SELECTION s [LIBNAME l])``.

    genreflex's dictionary, built into ``lib<name>_dictrflx.so`` - or
    ``LIBNAME`` - by test ``<prefix>-<name>-libgen-build``, which also sets up
    the fixture of its own name.
    """
    if not args:
        return
    parsed = parse_arguments(args[1:], ["NO_ROOTMAP"], ["SELECTION", "LIBNAME", *_FIXTURE_KEYS],
                             ["LIBRARIES", "OPTIONS", "COMPILE_OPTIONS"])
    name = targetname(self, args[0])
    ctest = name + "-libgen-build"
    selection = parsed.get("SELECTION", [""])[0]
    entry = Dictionary(args[0], self.relative, sources(self, parsed["UNPARSED"]),
                       selection=self.relative_path(selection) if selection else "",
                       includes=self.includes())
    libname = parsed.get("LIBNAME", [""])[0]
    target = library(self, name + "-libgen", [], parsed.get("LIBRARIES", []),
                     output=builds.library_name(libname) if libname else args[0] + "_dictrflx")
    target.dictionaries.append(entry)
    target.dictionary = True
    parsed["FIXTURES_SETUP"] = [ctest + "-fixture", *parsed.get("FIXTURES_SETUP", [])]
    _setup(self, ctest, "dictionary", list(entry.headers), parsed,
           builds=tuple(builds.library(self.registry, target)))
    self.variables["GENERATE_REFLEX_TEST"] = ctest


def _executable(self: Directory, args: list[str]) -> None:
    """``ROOTTEST_GENERATE_EXECUTABLE(exe sources...)``: a build, as ``<prefix>-<exe>-build``."""
    if not args:
        return
    parsed = parse_arguments(args[1:], [], ["RESOURCE_LOCK"],
                             ["LIBRARIES", "COMPILE_FLAGS", "DEPENDS", *_FIXTURE_KEYS])
    files = sources(self, parsed["UNPARSED"])
    self.registry.programs[args[0]] = Target(
        files, parsed.get("LIBRARIES", []), compiled=True, directory=self.relative,
        output=args[0], includes=self.includes())
    self.targets.add(args[0])
    ctest = targetname(self, args[0]) + "-build"
    _setup(self, ctest, "executable", files, parsed, program=args[0])
    self.variables["GENERATE_EXECUTABLE_TEST"] = ctest


# --- ROOTTEST_ADD_TEST ------------------------------------------------------


def add_test(self: Directory, args: list[str]) -> None:
    """``ROOTTEST_ADD_TEST(name MACRO|EXEC|COMMAND ... [OUTREF ...] ...)``."""
    if not args:
        return
    parsed = parse_arguments(args[1:], *_KEYWORDS)
    name = args[0]
    ctest = name if name.startswith("roottest-") else f"{prefix(self)}-{name}"
    if not _enabled(self, parsed):
        return
    parsed["DEPENDS"] = _depends(self, parsed.get("DEPENDS", []))
    parsed["FIXTURES_REQUIRED"] = [*parsed.get("FIXTURES_REQUIRED", []),
                                   *_depended_fixtures(self, parsed["DEPENDS"])]
    test_id = make_id("roottest", self.relative, _short(self, ctest))
    if parsed.get("COMMAND") and not parsed.get("MACRO") and not parsed.get("EXEC"):
        _command_test(self, parsed, test_id, ctest)
        return
    # ROOT's ROOTTEST_ADD_TEST hands every test's output to the driver as
    # `OUTPUT ${CMAKE_CURRENT_BINARY_DIR}/${testname}.log`, so a test that follows one reads
    # the file its sibling wrote there - `schemaRun2check`'s `sed schemaRun2.log`.
    self.registry.add(Test(id=test_id, ctest=ctest, kind=kind_of(ctest, self.relative),
                           directory=self.relative, store_out=True,
                           **_macro_or_exec(self, parsed), **_judging(self, parsed)))


def _enabled(self: Directory, parsed: dict[str, list[str]]) -> bool:
    """``ENABLE_IF``/``DISABLE_IF``: a test the build's features leave out is never registered."""
    features = self.registry.features
    enable, disable = parsed.get("ENABLE_IF"), parsed.get("DISABLE_IF")
    return not ((enable and enable[0] not in features) or (disable and disable[0] in features))


def _depends(self: Directory, given: list[str]) -> list[str]:
    """``DEPENDS``: a source file is compiled first, as its own test; a bare name is prefixed."""
    out = []
    for dep in given:
        if re.search(r"[.](C|cxx|h)", dep):
            out.append(_compile_macro(self, [dep, "FIXTURES_SETUP",
                                             f"compile-macro-{dep}-fixture"]))
        else:
            out.append(dep if dep.startswith("roottest-") else f"{prefix(self)}-{dep}")
    return out


def _depended_fixtures(self: Directory, depends: list[str]) -> list[str]:
    """The fixtures the tests it depends on set up, which ``ROOTTEST_ADD_TEST`` requires too.

    So a test whose dependency failed to set something up is not run, as in ctest.
    """
    registered = {test.ctest: test for test in self.registry.tests}
    return [fixture for dep in depends if dep in registered
            for fixture in registered[dep].fixtures_setup]


def _command_test(self: Directory, parsed: dict[str, list[str]], test_id: str,
                  ctest: str) -> None:
    """A ``COMMAND`` test: registered as ROOT_ADD_TEST would, then roottest's checks added.

    ``OPTS`` follow the command, as they follow a macro.
    """
    parsed = {**parsed, "COMMAND": [*parsed["COMMAND"], *parsed.get("OPTS", [])]}
    register_command(self, parsed, test_id, ctest)
    test = self.registry.tests.pop()
    checks = bool(parsed.get("OUTREF")) or "STOREOUT" in parsed
    judging = _judging(self, parsed)
    judging.update(check_out=checks, check_err=checks, store_out=True)
    fields = {**test.__dict__, **judging}
    self.registry.add(Test(**fields))


def _macro_or_exec(self: Directory, parsed: dict[str, list[str]]) -> dict[str, object]:
    """How ``ROOTTEST_SETUP_MACROTEST`` or ``ROOTTEST_SETUP_EXECTEST`` would run the test."""
    opts = tuple(parsed.get("OPTS", []))
    if parsed.get("EXEC"):
        exe = Path(parsed["EXEC"][0]).name
        return {"runner": "program", "program": exe, "command": (*parsed["EXEC"], *opts),
                "args": opts}
    macro = parsed.get("MACRO", [""])[0]
    path = macro.partition("(")[0].rstrip("+")
    asserting = macro.startswith("assert")
    if path.endswith(".py"):
        how: dict[str, object] = {"runner": "script", "files": (self.relative_path(path),),
                                  "args": (*self.values("PYROOT_EXTRAFLAGS"), *opts)}
    else:
        args = (*_root_options(self, parsed), _called(self, macro, parsed), *opts)
        found = self.inside(path) if path.endswith(_CXX) else None
        files = (found,) if found is not None else ()
        how = {"runner": "root", "args": args, "files": files}
    how.update(command=(macro,), check_out=not asserting, check_err=True)
    return how


def _root_options(self: Directory, parsed: dict[str, list[str]]) -> list[str]:
    """``ROOTTEST_SETUP_MACROTEST``'s ``root.exe`` options: the directory's compile definitions
    as ``#define`` lines, the build and macro paths set, ``ROOTEXE_OPTS``, then ``-q -b``."""
    build, source = f"<build>/{self.relative}", str(self.source)
    defines = [f"#define {name}" for name in self.values(DEFINITIONS)
               if not any(word in name for word in ("_WIN32", "_XKEYCHECK_H", "NOMINMAX"))]
    lines = [*defines, f'gSystem->SetBuildDir("{build}",true)',
             f'gSystem->AddDynamicPath("{build}")', f'gROOT->SetMacroPath("{source}")',
             f'gInterpreter->AddIncludePath("-I{build}")', f'gSystem->AddIncludePath("-I{build}")']
    return [*(word for line in lines for word in ("-e", line)),
            *parsed.get("ROOTEXE_OPTS", []), "-q", "-b"]


def _called(self: Directory, macro: str, parsed: dict[str, list[str]]) -> str:
    """The macro as ``root.exe`` is given it: its real path, ``+`` kept, ``MACROARG`` called.

    Only a C++ macro is made a path; anything else - a command - is passed as written.
    """
    plain, paren, inline = macro.partition("(")
    path = plain.rstrip("+")
    if not path.endswith(_CXX):
        return macro
    real = path if path.startswith("<build>/") else str(self.path(path).resolve())
    called = real + plain[len(path):]
    if parsed.get("MACROARG"):
        return f"{called}({parsed['MACROARG'][0]})"
    return called + paren + inline


def _judging(self: Directory, parsed: dict[str, list[str]]) -> dict[str, object]:
    """The driver's checks: the references, the return code, the regexes, and what is skipped."""
    return {
        **_references(self, parsed), **_numbers(parsed),
        "passregex": tuple(parsed.get("PASSREGEX", [])),
        "failregex": tuple(parsed.get("FAILREGEX", [])),
        "will_fail": "WILLFAIL" in parsed, "custom_diff": True,
        "depends": tuple(parsed.get("DEPENDS", [])),
        "fixtures_setup": tuple(parsed.get("FIXTURES_SETUP", [])),
        "fixtures_required": tuple(parsed.get("FIXTURES_REQUIRED", [])),
        "labels": tuple(parsed.get("LABELS", [])),
        "environment": tuple(parsed.get("ENVIRONMENT", [])),
        "python_deps": tuple(parsed.get("PYTHON_DEPS", [])),
        "working_dir": working_dir(self, parsed),
        "copy": tuple(self.relative_path(name) for name in parsed.get("COPY_TO_BUILDDIR", [])),
        "precmd": tuple(parsed.get("PRECMD", [])),
        "postcmd": tuple(parsed.get("POSTCMD", [])),
    }


def _first(parsed: dict[str, list[str]], *keys: str) -> str:
    """The value of the first of ``keys`` given, or ``""``."""
    return next((parsed[key][0] for key in keys if parsed.get(key)), "")


def _references(self: Directory, parsed: dict[str, list[str]]) -> dict[str, object]:
    return {
        "outref": _reference(self, _first(parsed, "OUTREF_CINTSPECIFIC", "OUTREF"), bits=True),
        "errref": _reference(self, _first(parsed, "ERRREF")),
        "outcnv": _reference(self, _first(parsed, "OUTCNV")),
        "outcnvcmd": tuple(parsed.get("OUTCNVCMD", [])),
        "input": _reference(self, _first(parsed, "INPUT")),
    }


def _numbers(parsed: dict[str, list[str]]) -> dict[str, object]:
    passrc, timeout = _first(parsed, "PASSRC"), _first(parsed, "TIMEOUT")
    return {
        "passrc": int(passrc) if passrc.lstrip("-").isdigit() else None,
        "timeout": float(timeout) if timeout.isdigit() else None,
    }


def _reference(self: Directory, given: str, bits: bool = False) -> str:
    """A reference file below ROOT; ``x.ref64`` instead of ``x.ref`` when there is one."""
    if not given:
        return ""
    if bits and self.path(given + "64").is_file():
        given += "64"
    return self.relative_path(given)


# --- directories and helpers ------------------------------------------------


def _automacros(self: Directory, args: list[str]) -> None:
    """``ROOTTEST_ADD_AUTOMACROS``: every ``run*``, ``exec*`` and ``assert*`` macro is a test."""
    parsed = parse_arguments(args, [], [], ["DEPENDS", "WILLFAIL", "EXCLUDE", *_FIXTURE_KEYS])
    names = sorted({path.name for pattern in ("run*", "assert*", "exec*")
                    for path in self.source.glob(pattern) if path.suffix in (".C", ".cxx")})
    for filename in names:
        stem = filename.split(".")[0]
        if any(re.search(pattern, stem) for pattern in parsed.get("EXCLUDE", [])):
            continue
        add_test(self, _automacro_args(self, filename, parsed))


def _automacro_args(self: Directory, filename: str, parsed: dict[str, list[str]]) -> list[str]:
    stem = filename.split(".")[0]
    sub = re.sub(r"^(run|exec)", "", stem)
    ref = next((name + ".ref" for name in (stem, sub) if self.path(name + ".ref").is_file()), "")
    args = [targetname(self, filename) + "-auto", "MACRO",
            filename + self.variables.get(f"{stem}-suffix", "")]
    if ref:
        args += ["OUTREF", ref]
    if any(re.search(pattern, stem) for pattern in parsed.get("WILLFAIL", [])):
        args.append("WILLFAIL")
    for key in ("DEPENDS", *_FIXTURE_KEYS):
        if parsed.get(key):
            args += [key, *parsed[key]]
    return args


def _testdirs(self: Directory, args: list[str]) -> None:
    """``ROOTTEST_ADD_TESTDIRS``: every subdirectory with a CMakeLists, in sorted order."""
    parsed = parse_arguments(args, [], [], ["EXCLUDED_DIRS"])
    excluded = set(parsed.get("EXCLUDED_DIRS", []))
    for child in sorted(self.source.iterdir()):
        if child.name not in excluded and (child / "CMakeLists.txt").is_file():
            self.subdirectory(f"{self.relative}/{child.name}")


def _unittest_dir(self: Directory, args: list[str]) -> None:
    """``ROOTTEST_ADD_UNITTEST_DIR``: its sources as one gtest, ``<prefix>_unittests``."""
    parsed = parse_arguments(args, ["WILLFAIL"], [],
                             ["COPY_TO_BUILDDIR", "DEPENDS", "OPTS", "LABELS", "ENVIRONMENT"])
    files = sorted(path.name for path in self.source.iterdir() if path.suffix in _CXX)
    exe = prefix(self) + "_exe"
    self.registry.programs[exe] = Target(sources(self, files), parsed["UNPARSED"],
                                         directory=self.relative, output=exe,
                                         includes=self.includes())
    ctest = prefix(self) + "_unittests"
    self.registry.add(Test(
        id=make_id("roottest", self.relative, "unittests"), ctest=ctest, kind="roottest",
        directory=self.relative, runner="gtest", program=exe, will_fail="WILLFAIL" in parsed,
        check_out=False, check_err=False))


def _oldtest(self: Directory, args: list[str]) -> None:
    ctest = prefix(self) + "-make"
    self.registry.add(Test(
        id=make_id("roottest", self.relative, "make"), ctest=ctest, kind="roottest",
        directory=self.relative, runner="command", command=("make", "cleantest"),
        skip="runs roottest's old Makefile, which builds and runs C++ with a compiler"))


def _targetname_command(self: Directory, args: list[str]) -> None:
    if len(args) >= 2:
        self.variables[args[0]] = targetname(self, args[1])


def _find_python_module(self: Directory, args: list[str]) -> None:
    """roottest's ``find_python_module``: CI's Python is taken to have what ROOT's tests use."""
    if args:
        upper = args[0].upper()
        self.variables.update({f"PY_{upper}": args[0], f"PY_{upper}_FOUND": "TRUE"})


